import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

type Result = { n: number; title: string; ok: boolean; proof: string[] };

export function createReport() {
  const results: Result[] = [];
  const started = new Date();

  return {
    started,
    passed: () => results.every((r) => r.ok),

    async check(n: number, title: string, prove: () => Promise<string[]>) {
      process.stdout.write(`${String(n).padStart(2)}. ${title} ... `);
      try {
        results.push({ n, title, ok: true, proof: await prove() });
        console.log("ok");
      } catch (error) {
        results.push({
          n,
          title,
          ok: false,
          proof: [error instanceof Error ? error.message : String(error)],
        });
        console.log("FAILED");
      }
    },

    write(file: string, header: string) {
      const passed = results.filter((r) => r.ok).length;
      const lines = [
        "# M1 acceptance run",
        "",
        `Run ${started.toISOString()} to ${new Date().toISOString()}. ${header}`,
        "Generated by `pnpm --filter @forgeops/api acceptance` (apps/api/src/acceptance/).",
        "",
        `**${passed} of ${results.length} criteria passed.**`,
        "",
        "| # | Criterion | Result |",
        "| --- | --- | --- |",
        ...results.map((r) => `| ${r.n} | ${r.title} | ${r.ok ? "Passed" : "**Failed**"} |`),
        "",
        ...results.flatMap((r) => [
          `## ${r.n}. ${r.title}: ${r.ok ? "passed" : "FAILED"}`,
          "",
          ...r.proof.map((p) => `- ${p.replace(/\n/g, " ").slice(0, 600)}`),
          "",
        ]),
      ];
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, lines.join("\n"));
      console.log(`\n${passed}/${results.length} passed. Evidence: ${file}`);
    },
  };
}
